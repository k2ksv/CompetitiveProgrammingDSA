mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());
auto randint(ll l, ll r) { return uniform_int_distribution<ll>(l,r)(rng); }

const ll  INF = 2e18;
const int MOD = 1e9 + 7;

void Solve() {
    int n;
    ll a, b;
    cin >> n >> a >> b;

    ll g = std::gcd(a, b);
    vector<ll> c(n);
    
    for (int i = 0; i < n; i++) {
        cin >> c[i];
        c[i] %= g; 
    }
    sort(c.begin(), c.end());
    ll min_range = c[n - 1] - c[0];
    for (int i = 0; i < n - 1; i++) {
        ll current_range = (c[i] + g) - c[i + 1];
        min_range = min(min_range, current_range);
    }

    cout << min_range << '\n';
}

